#!/usr/bin/env python3
"""Generate a text-provider snap's plugin artefacts from plugins/*.toml.

    dev/gen-plugins.py [--check] <snap-dir>...
    dev/gen-plugins.py --list-files <snap-dir>

One plugins/<name>.toml per model component is the only hand-edited source.
It yields, deterministically:

  - the `components:` stanza and the model-components `organize:` mappings
    of snap/snapcraft.yaml, between the BEGIN/END generated markers;
  - models/<name>/myna-text-model.json and models/<name>/NOTICE;
  - catalog.json for the snap.

quality, latency_ms and their source come from plugins/<name>.measured.json,
written by the evaluation pipeline, never typed into the toml. --check
regenerates in memory and fails when a committed file differs.
Contract: .kb/text-plugin-contract.md.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

CATALOG_VERSION = 1
LICENSES = ("Apache-2.0", "MIT", "MPL-2.0", "CC-BY-4.0")
STAGES = ("field-fit", "clean-up", "translate", "target-language")
CLASSES = ("edit", "translate", "rewrite")
NEEDS = ("sentence", "dictation")
COMMON_LICENSES = Path("/usr/share/common-licenses")
BEGIN = "# BEGIN generated by dev/gen-plugins.py, do not edit"
END = "# END generated by dev/gen-plugins.py"
COMPONENT_RE = re.compile(r"^model-[a-z0-9]+(-[a-z0-9]+)+$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")
REQUIRED = (
    "id component snap kind task class needs language license attribution source "
    "download_bytes entry_revision curated pin locales summary description notice"
).split()


class PluginError(Exception):
    pass


def licence_allowed(name: str) -> bool:
    return name in LICENSES or re.fullmatch(r"BSD(-[0-9]-Clause)?", name) is not None


def read_plugin(path: Path) -> dict:
    plugin = tomllib.loads(path.read_text(encoding="utf-8"))
    plugin["name"] = path.stem
    measured = path.with_suffix(".measured.json")
    if not measured.is_file():
        raise PluginError(f"{path}: no {measured.name}")
    plugin["measured"] = json.loads(measured.read_text(encoding="utf-8"))
    return plugin


def validate(plugin: dict, source: str = "plugin") -> None:
    def bad(msg: str) -> PluginError:
        return PluginError(f"{source}: {msg}")

    for key in REQUIRED:
        if key not in plugin:
            raise bad(f"missing {key}")
    component = plugin["component"]
    if not COMPONENT_RE.fullmatch(component) or component != f"model-{plugin['name']}":
        raise bad(f"component {component!r} must be model-<file stem>")
    if plugin["class"] not in CLASSES:
        raise bad(f"class {plugin['class']!r} not in {CLASSES}")
    if plugin["needs"] not in NEEDS:
        raise bad(f"needs {plugin['needs']!r} not in {NEEDS}")
    if not licence_allowed(plugin["license"]):
        raise bad(f"licence {plugin['license']!r} is not on the allow-list")
    if plugin["license"] not in ("Apache-2.0", "MPL-2.0") and "license_file" not in plugin:
        raise bad("license_file is required for a licence without a common-licenses text")
    for key in ("download_bytes", "entry_revision"):
        if type(plugin[key]) is not int or plugin[key] < 1:
            raise bad(f"{key} must be a positive integer")
    if not isinstance(plugin["curated"], bool):
        raise bad("curated must be a boolean")
    if not plugin["locales"] or not all(isinstance(x, str) for x in plugin["locales"]):
        raise bad("locales must be a non-empty list of language codes")
    step = plugin.get("step", {})
    if not re.fullmatch(r"[a-z][a-z0-9-]*", step.get("id", "")):
        raise bad("step.id must be a kebab-case id")
    if step.get("stage") not in STAGES:
        raise bad(f"step.stage not in {STAGES}")
    hardware = plugin.get("hardware", {})
    if not hardware.get("arch") or not isinstance(hardware.get("min_ram_mb"), int):
        raise bad("hardware needs arch and min_ram_mb")
    files = plugin.get("files", [])
    if not files:
        raise bad("no [[files]]")
    for entry in files:
        if not SHA_RE.fullmatch(entry.get("sha256", "")):
            raise bad(f"file {entry.get('name')!r}: sha256 is not 64 lowercase hex")
        if not isinstance(entry.get("bytes"), int) or entry["bytes"] < 1:
            raise bad(f"file {entry.get('name')!r}: bytes must be a positive integer")
        if "url" not in entry and "local" not in plugin:
            raise bad(f"file {entry['name']!r}: no url and no [local] source")
    if "local" in plugin and not {"env", "default"} <= plugin["local"].keys():
        raise bad("[local] needs env and default")
    for param in plugin.get("params", []):
        if param.get("kind") not in ("language", "text") or param.get("role") not in (
            "source",
            "target",
            "free",
        ):
            raise bad(f"bad param {param!r}")
    measured = plugin["measured"]
    if not (
        isinstance(measured.get("quality"), (int, float))
        and 0 <= measured["quality"] <= 1
        and isinstance(measured.get("latency_ms"), int)
        and measured["latency_ms"] > 0
        and measured.get("quality_source")
    ):
        raise bad("measured.json needs quality 0..1, latency_ms and quality_source")


def latency_class(ms: int) -> str:
    return "fast" if ms < 50 else "ok" if ms < 400 else "slow"


def manifest_of(plugin: dict) -> dict:
    m = plugin["measured"]
    out: dict = {
        "contract": 2,
        "kind": plugin["kind"],
        "id": plugin["id"],
        "task": plugin["task"],
        "class": plugin["class"],
        "needs": plugin["needs"],
        "params": plugin["params"] if "params" in plugin else [],
        "language": plugin["language"],
    }
    if "to" in plugin:
        out["to"] = plugin["to"]
    out["latency_ms"] = m["latency_ms"]
    out["quality"] = m["quality"]
    for key in ("tau", "config"):
        if key in plugin:
            out[key] = plugin[key]
    for key in ("license", "attribution", "download_bytes", "source"):
        out[key] = plugin[key]
    return out


def dump_manifest(manifest: dict) -> str:
    # Params stay one per line, as the hand-written manifests had them.
    body = dict(manifest)
    params = body.pop("params")
    lines = json.dumps(body, indent=2, ensure_ascii=False).splitlines()
    lines.insert(
        [i for i, ln in enumerate(lines) if ln.startswith('  "needs"')][0] + 1,
        '  "params": [\n'
        + ",\n".join("    " + json.dumps(p, ensure_ascii=False) for p in params)
        + "\n  ],",
    )
    return "\n".join(lines) + "\n"


def notice_of(plugin: dict) -> str:
    out = plugin["notice"].rstrip("\n") + "\n\n"
    width = max(len(f["name"]) for f in plugin["files"])
    for f in plugin["files"]:
        out += f"  {f['name']:<{width}}  {f['sha256']}\n"
    if "notice_tail" in plugin:
        out += "\n" + plugin["notice_tail"].rstrip("\n") + "\n"
    return out


def catalog_entry(plugin: dict) -> dict:
    m = plugin["measured"]
    step = plugin["step"]
    covers = {"language": plugin["language"]}
    if "to" in plugin:
        covers["to"] = plugin["to"]
    entry = {
        "id": plugin["component"],
        "snap": plugin["snap"],
        "component": plugin["component"],
        "model": plugin["id"],
        "contract": 2,
        "entry_revision": plugin["entry_revision"],
        "task": plugin["task"],
        "class": plugin["class"],
        "needs": plugin["needs"],
        "params": plugin.get("params", []),
        "covers": covers,
        "in_lang": plugin["language"],
        "out_lang": plugin.get("to", plugin["language"]),
        "step": {
            "id": step["id"],
            "stage": step["stage"],
            "label_key": f"step.{step['id']}.name",
            "description_key": f"step.{step['id']}.description",
            "example_key": f"step.{step['id']}.example",
        },
        "download_bytes": plugin["download_bytes"],
        "installed_bytes": sum(f["bytes"] for f in plugin["files"]),
        "quality": {"value": m["quality"], "source": m["quality_source"]},
        "latency_ms": m["latency_ms"],
        "latency_class": latency_class(m["latency_ms"]),
        "hardware": plugin["hardware"],
        "locales": plugin["locales"],
        "curated": plugin["curated"],
        "license": plugin["license"],
        "attribution": plugin["attribution"],
        "source": plugin["source"],
        "files": [
            {k: f[k] for k in ("name", "sha256", "bytes", "url") if k in f} for f in plugin["files"]
        ],
    }
    return entry


def indented(text: str, pad: str) -> str:
    return "".join(pad + ln if ln else ln for ln in text.splitlines(True))


def components_block(plugins: list[dict]) -> str:
    out = ""
    for p in plugins:
        out += (
            f"  {p['component']}:\n    type: standard\n    summary: {p['summary']}\n"
            "    description: |\n" + indented(p["description"].rstrip("\n") + "\n", "      ")
        )
    return out


def organize_block(plugins: list[dict]) -> str:
    return "".join(f'      "{p["component"]}/*": (component/{p["component"]})/\n' for p in plugins)


def splice(text: str, block: str, indent: str, label: str) -> str:
    pattern = re.compile(
        rf"^{indent}{re.escape(BEGIN)} \({label}\)\n.*?^{indent}{re.escape(END)} \({label}\)\n",
        re.S | re.M,
    )
    if not pattern.search(text):
        raise PluginError(f"snapcraft.yaml has no generated {label} markers")
    new = f"{indent}{BEGIN} ({label})\n{block}{indent}{END} ({label})\n"
    return pattern.sub(lambda _: new, text)


def outputs_of(snap_dir: Path) -> dict[Path, str]:
    paths = sorted((snap_dir / "plugins").glob("*.toml"))
    if not paths:
        raise PluginError(f"{snap_dir}: no plugins/*.toml")
    plugins = [read_plugin(p) for p in paths]
    for p, path in zip(plugins, paths, strict=True):
        validate(p, str(path))
        if p["snap"] != f"myna-{snap_dir.name.removesuffix('-snap')}":
            raise PluginError(f"{path}: snap {p['snap']!r} is not this directory's snap")
    out: dict[Path, str] = {}
    for p in plugins:
        models = snap_dir / "models" / p["name"]
        out[models / "myna-text-model.json"] = dump_manifest(manifest_of(p))
        out[models / "NOTICE"] = notice_of(p)
    recipe = snap_dir / "snap/snapcraft.yaml"
    text = recipe.read_text(encoding="utf-8")
    text = splice(text, organize_block(plugins), "      ", "organize")
    text = splice(text, components_block(plugins), "  ", "components")
    out[recipe] = text
    catalog = {
        "catalog": CATALOG_VERSION,
        "snap": plugins[0]["snap"],
        "plugins": [catalog_entry(p) for p in plugins],
    }
    out[snap_dir / "catalog.json"] = json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"
    return out


def list_files(snap_dir: Path) -> str:
    """Tab-separated staging plan for dev/stage-plugins.sh; '-' is empty."""
    out = ""
    for path in sorted((snap_dir / "plugins").glob("*.toml")):
        p = read_plugin(path)
        validate(p, str(path))
        license_file = p.get("license_file") or str(COMMON_LICENSES / p["license"])
        local = p.get("local", {})
        out += (
            "\t".join(
                [
                    "P",
                    p["snap"],
                    p["component"],
                    p["name"],
                    p["pin"],
                    license_file,
                    local.get("env", "-"),
                    local.get("default", "-"),
                ]
            )
            + "\n"
        )
        for f in p["files"]:
            out += (
                "\t".join(["F", p["component"], f["name"], f["sha256"], f.get("url", "-")]) + "\n"
            )
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file differs")
    ap.add_argument("--list-files", action="store_true", help="print the staging plan")
    ap.add_argument("snap_dir", nargs="+", type=Path)
    args = ap.parse_args(argv)
    try:
        if args.list_files:
            for snap_dir in args.snap_dir:
                sys.stdout.write(list_files(snap_dir.resolve()))
            return 0
        stale = []
        for snap_dir in args.snap_dir:
            for path, text in outputs_of(snap_dir.resolve()).items():
                current = path.read_text(encoding="utf-8") if path.is_file() else None
                if current == text:
                    continue
                if args.check:
                    stale.append(path)
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8")
                    print(f"wrote {path}")
    except PluginError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    if stale:
        for path in stale:
            print(f"stale: {path} (run dev/gen-plugins.py on its snap dir)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
